using namespace std;

typedef long long i64;

void solve() {
    int n, root;
    cin >> n >> root;
    vector<int> a(n);
    input(a);
    vector g(n, vector<int>());
    for (int i = 0; i < n; ++i) {
        int u, v;
        cin >> u >> v;
        --u; --v;
        g[u].push_back(v);
        g[v].push_back(u);
    }
    
    return;
}

